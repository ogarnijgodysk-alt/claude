import JSZip from "jszip";
import { newId, readDb, updateDb } from "../db";
import { readStored, saveBuffer, saveText, saveUpload } from "../files";
import { demoJobDone, demoPortraitSvg } from "../providers/demo";
import { cloneVoice, hasElevenLabs } from "../providers/elevenlabs";
import { hasFal, pollPortraitTraining, startPortraitTraining } from "../providers/fal";
import { createAvatar, getAvatarLook, hasHeygen, startConsent } from "../providers/heygen";
import type { Clone, CloneKind, CloneVoice } from "../types";

export interface CreateCloneInput {
  kind: CloneKind;
  name: string;
  description: string;
  subjectName: string;
  consentConfirmed: boolean;
  trainingVideo?: File;
  consentVideo?: File;
  cover?: File;
  /** Face picked in the influencer wizard: a remote URL or an already stored file name. */
  coverRef?: string;
  photos: File[];
  voiceSample?: File;
  voiceProvider?: "heygen" | "elevenlabs";
  voiceId?: string;
}

const MIN_PHOTOS = 8;

function validate(input: CreateCloneInput) {
  if (!input.name.trim()) throw new Error("Podaj nazwę klona.");
  if (input.kind !== "ai_influencer" && !input.consentConfirmed) {
    throw new Error("Klon realnej osoby wymaga jej świadomej zgody.");
  }
  if (input.kind === "digital_twin" && !input.trainingVideo) throw new Error("Nagraj lub dodaj wideo treningowe.");
  if (input.kind === "photo_clone" && input.photos.length < MIN_PHOTOS) {
    throw new Error(`Dodaj co najmniej ${MIN_PHOTOS} zdjęć twarzy (najlepiej 15–20).`);
  }
  if (input.kind === "ai_influencer" && !input.coverRef) throw new Error("Wybierz twarz influencera.");
}

async function storeCoverRef(ref: string) {
  if (!/^https?:\/\//.test(ref)) {
    await readStored(ref); // throws on unknown / unsafe names
    return ref;
  }
  // Only faces generated by fal.ai are fetched server-side; anything else would be an open proxy.
  const host = new URL(ref).hostname;
  if (host !== "fal.media" && !host.endsWith(".fal.media")) throw new Error("Nieobsługiwany adres zdjęcia.");
  const res = await fetch(ref);
  if (!res.ok) throw new Error("Nie udało się pobrać wybranego zdjęcia.");
  return saveBuffer(Buffer.from(await res.arrayBuffer()), res.headers.get("content-type") ?? "image/jpeg", "cover");
}

async function zipPhotos(files: File[]) {
  const zip = new JSZip();
  for (const [i, f] of files.entries()) {
    zip.file(`${i}.${f.type === "image/png" ? "png" : "jpg"}`, new Uint8Array(await f.arrayBuffer()));
  }
  return new Blob([await zip.generateAsync({ type: "arraybuffer" })], { type: "application/zip" });
}

export async function createClone(input: CreateCloneInput): Promise<Clone> {
  validate(input);
  const id = newId("cl");
  const live = hasHeygen();

  const clone: Clone = {
    id,
    kind: input.kind,
    name: input.name.trim(),
    description: input.description.trim(),
    status: "processing",
    photoFiles: [],
    voice: { provider: "none" },
    consent: {
      confirmed: input.kind === "ai_influencer" ? true : input.consentConfirmed,
      subjectName: input.subjectName.trim(),
      at: new Date().toISOString(),
    },
    demo: !live,
    createdAt: new Date().toISOString(),
  };

  if (input.trainingVideo) clone.trainingVideoFile = await saveUpload(input.trainingVideo, "train");
  if (input.consentVideo) clone.consentVideoFile = await saveUpload(input.consentVideo, "consent");
  for (const p of input.photos) clone.photoFiles.push(await saveUpload(p, "photo"));

  if (input.coverRef) clone.coverFile = await storeCoverRef(input.coverRef);
  else if (input.cover) clone.coverFile = await saveUpload(input.cover, "cover");
  else if (clone.photoFiles[0]) clone.coverFile = clone.photoFiles[0];
  else clone.coverFile = await saveText(demoPortraitSvg(id, clone.name), "image/svg+xml", "cover");

  clone.voice = await setupVoice(clone, input);

  try {
    if (live) {
      if (input.kind === "digital_twin") {
        const { avatarId, groupId } = await createAvatar("digital_twin", clone.name, clone.trainingVideoFile!);
        clone.heygen = { avatarId, groupId };
        if (groupId) clone.heygen.consentUrl = await startConsent(groupId);
      } else {
        const { avatarId, groupId } = await createAvatar("photo", clone.name, clone.coverFile);
        clone.heygen = { avatarId, groupId };
      }
    }
    if (input.kind === "photo_clone") {
      if (hasFal()) {
        const triggerWord = `TOK${id.slice(-6).toUpperCase()}`;
        const requestId = await startPortraitTraining(await zipPhotos(input.photos), triggerWord);
        clone.fal = { trainingRequestId: requestId, triggerWord };
      }
      clone.loraStatus = "processing";
    }
  } catch (err) {
    clone.status = "failed";
    clone.error = err instanceof Error ? err.message : String(err);
  }

  await updateDb((db) => {
    db.clones.unshift(clone);
  });
  return clone;
}

async function setupVoice(clone: Clone, input: CreateCloneInput): Promise<CloneVoice> {
  if (input.voiceId?.trim() && input.voiceProvider) {
    return { provider: input.voiceProvider, voiceId: input.voiceId.trim() };
  }
  if (input.voiceSample) {
    const sampleFile = await saveUpload(input.voiceSample, "voice");
    if (hasElevenLabs()) {
      const voiceId = await cloneVoice(clone.name, sampleFile, clone.description);
      return { provider: "elevenlabs", voiceId, sampleFile };
    }
    return { provider: "none", sampleFile };
  }
  // A HeyGen digital twin clones the voice from its training footage.
  if (clone.kind === "digital_twin") return { provider: "heygen" };
  return { provider: "none" };
}

/** Pulls fresh training state from the providers for a clone still in progress. */
export async function refreshClone(id: string): Promise<Clone | undefined> {
  const current = (await readDb()).clones.find((c) => c.id === id);
  if (!current) return undefined;
  const patch: Partial<Clone> = {};

  try {
    if (current.status === "processing") {
      if (current.demo || !current.heygen?.avatarId) {
        if (demoJobDone(current.createdAt)) patch.status = "ready";
      } else {
        const look = await getAvatarLook(current.heygen.avatarId);
        patch.heygen = { ...current.heygen, consentStatus: look.consentStatus };
        if (look.state === "ready") patch.status = "ready";
        if (look.state === "failed") {
          patch.status = "failed";
          patch.error = look.error ?? "Trening awatara w HeyGen nie powiódł się.";
        }
        if (look.voiceId && current.voice.provider === "heygen" && !current.voice.voiceId) {
          patch.voice = { ...current.voice, voiceId: look.voiceId };
        }
      }
    }
    if (current.loraStatus === "processing") {
      if (!current.fal?.trainingRequestId) {
        if (demoJobDone(current.createdAt)) patch.loraStatus = "ready";
      } else {
        const job = await pollPortraitTraining(current.fal.trainingRequestId);
        if (job.status === "ready") {
          patch.loraStatus = "ready";
          patch.fal = { ...current.fal, loraUrl: job.result as string };
        } else if (job.status === "failed") {
          patch.loraStatus = "failed";
          patch.error = job.error;
        }
      }
    }
  } catch (err) {
    // Transient provider errors shouldn't fail the clone; the next poll retries.
    console.error(`refreshClone ${id}:`, err);
  }

  if (Object.keys(patch).length === 0) return current;
  return updateDb((db) => {
    const c = db.clones.find((x) => x.id === id);
    if (c) Object.assign(c, patch);
    return c;
  });
}

export async function renewConsentLink(id: string) {
  const clone = (await readDb()).clones.find((c) => c.id === id);
  if (!clone?.heygen?.groupId) throw new Error("Ten klon nie wymaga zgody w HeyGen.");
  const consentUrl = await startConsent(clone.heygen.groupId);
  return updateDb((db) => {
    const c = db.clones.find((x) => x.id === id)!;
    c.heygen = { ...c.heygen, consentUrl };
    return c;
  });
}

export async function updateCloneVoice(id: string, voice: CloneVoice) {
  return updateDb((db) => {
    const c = db.clones.find((x) => x.id === id);
    if (!c) throw new Error("Nie znaleziono klona.");
    c.voice = { ...c.voice, ...voice };
    return c;
  });
}

export async function deleteClone(id: string) {
  await updateDb((db) => {
    db.clones = db.clones.filter((c) => c.id !== id);
  });
}
